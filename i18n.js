const translations = copy.split('\n')
  .map(line => line.split('|'))
  .filter(([zh, en]) => zh?.trim() && en?.trim());
const zhToEn = new Map(translations);
const enToZh = new Map([...zhToEn].map(([zh,en]) => [en,zh]));
let language = 'zh';
const originalText = new WeakMap();
function translateNode(node) {
  let record = originalText.get(node);
  const current = node.nodeValue;
  if (!record || current !== record.rendered) record = {original:current, rendered:current};
  const trimmed = record.original.trim();
  const output = trimmed && language === 'en' && zhToEn.has(trimmed)
    ? record.original.replace(trimmed, zhToEn.get(trimmed)) : record.original;
  record.rendered = output;
  originalText.set(node, record);
  if (current !== output) node.nodeValue = output;
}
function translatePage() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    if (!node.parentElement.closest('script,style,#languageToggle')) translateNode(node);
  }
  document.querySelectorAll('[aria-label]:not(#languageToggle)').forEach(el => { const dict = language === 'en' ? zhToEn : enToZh; const label = el.getAttribute('aria-label'); if (dict.has(label)) el.setAttribute('aria-label', dict.get(label)); });
  document.querySelectorAll('img[alt]').forEach(img => {
    const dict = language === 'en' ? zhToEn : enToZh;
    if (dict.has(img.alt)) img.alt = dict.get(img.alt);
  });
}
const languageButton = document.getElementById('languageToggle');
function setLanguage(next) {
  language = next;
  document.documentElement.lang = next === 'en' ? 'en' : 'zh-CN';
  document.title = next === 'en' ? 'pillovox · Pillovox Bone Conduction Sleep Pillow' : 'pillovox 枕语 · Pillovox 骨传导睡眠枕';
  if (document.body.dataset.page === 'journey') document.title = next === 'en' ? 'Somni Team · Team stories' : 'Somni 团队 · 团队故事';
  languageButton.textContent = next === 'en' ? '中文' : 'EN';
  languageButton.setAttribute('aria-label', next === 'en' ? '切换为中文' : 'Switch to English');
  translatePage();
  try { localStorage.setItem('pillovox-language', next); } catch {}
}
languageButton.addEventListener('click', () => setLanguage(language === 'en' ? 'zh' : 'en'));
